export const NO_NEARBY_STATION = '가까운 역 없음'

function normalizeStationQuery(value: string) {
  return value.replace(/\s+/g, '').replace(/역$/u, '').toLowerCase()
}

export function formatStationLabel(station: SubwayStation) {
  return station.name.endsWith('역') ? station.name : `${station.name}역`
}

export function searchStations(query: string, city?: string | null) {
  const scoped = city
    ? SUBWAY_STATIONS.filter((station) => station.city === city)
    : SUBWAY_STATIONS
  const q = normalizeStationQuery(query)

  if (!q) return []

  const scored = scoped
    .map((station) => {
      const name = normalizeStationQuery(station.name)
      if (name === q) return { station, score: 100 }
      if (name.startsWith(q)) return { station, score: 80 }
      if (name.includes(q)) return { station, score: 50 }
      return null
    })
    .filter((item): item is { station: SubwayStation; score: number } =>
      Boolean(item),
    )

  return scored
    .sort((a, b) => b.score - a.score)
    .slice(0, 12)
    .map((item) => item.station)
}
